import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { generateStyleProject } from "./style-generator.mjs";

const manifest = {
  contract: "style-manifest.v1",
  id: "style-generated-safe",
  name: "Generated safe style",
  version: 1,
  status: "draft",
  sourceAnalysisId: "analysis-generator",
  supportedModes: ["single-video-v1", "multi-asset-v1"],
  parameters: { captionScale: 1, motionIntensity: 0.8 },
  capabilities: ["captions", "title_card"],
  requirements: { minAssets: 2, needsMainFootage: true, needsBroll: false },
  unsupported: [],
  preview: null,
};
const analysis = { analysisId: "analysis-generator" };
const root = await fs.mkdtemp(path.join(os.tmpdir(), "wayne-style-generator-"));

try {
  const fakeCli = path.join(root, "fake-claude.sh");
  const cliCapture = path.join(root, "claude-args.txt");
  await fs.writeFile(fakeCli, [
    "#!/bin/sh",
    `printf '%s\\n' \"$@\" > '${cliCapture.replaceAll("'", "'\\''")}'`,
    "printf '\\n// generated by fake claude cli\\n' >> src/StyleOverlay.tsx",
    "exit 0",
    "",
  ].join("\n"), { mode: 0o755 });
  const previousClaudeBin = process.env.CLAUDE_BIN;
  process.env.CLAUDE_BIN = fakeCli;
  try {
    const cliGenerated = await generateStyleProject({
      analysis,
      manifest: { ...manifest, id: "style-generated-cli" },
      outDir: path.join(root, "cli-generated"),
    });
    assert.equal(cliGenerated.status, "draft");
    const args = await fs.readFile(cliCapture, "utf8");
    assert.match(args, /--bare/);
    assert.match(args, /--restricted/);
    assert.match(args, /--permission-mode/);
    assert.match(args, /Read,Edit,Write/);
    assert.match(args, /Never use fetch/);
    assert.match(args, /Style manifest:/);
    assert.match(args, /StyleSpec v2/);
  } finally {
    if (previousClaudeBin == null) delete process.env.CLAUDE_BIN;
    else process.env.CLAUDE_BIN = previousClaudeBin;
  }

  const safeDir = path.join(root, "safe");
  const safe = await generateStyleProject({
    analysis,
    manifest,
    outDir: safeDir,
    claudeRunner: async ({ projectDir }) => {
      await fs.appendFile(path.join(projectDir, "src", "StyleOverlay.tsx"), "\n// generated by fake claude\n");
    },
  });
  assert.equal(safe.status, "draft");
  assert.match(safe.codeSha256, /^[a-f0-9]{64}$/);
  assert.equal((await fs.stat(path.join(safeDir, "style-manifest.json"))).isFile(), true);

  const unsafeDir = path.join(root, "unsafe");
  await assert.rejects(
    generateStyleProject({
      analysis,
      manifest: { ...manifest, id: "style-generated-unsafe" },
      outDir: unsafeDir,
      claudeRunner: async ({ projectDir }) => {
        await fs.appendFile(path.join(projectDir, "src", "StyleOverlay.tsx"), '\nfetch("https://evil.example");\n');
      },
    }),
    /policy|forbidden|fetch|network/i,
  );
  await assert.rejects(fs.access(path.join(unsafeDir, "style-manifest.json")), /ENOENT/);
} finally {
  await fs.rm(root, { recursive: true, force: true });
}

console.log("style-generator.verify: Claude CLI args, safe generation, policy rejection, and failed-generation cleanup passed");
